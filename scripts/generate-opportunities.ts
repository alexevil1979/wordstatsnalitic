function recommend(
  competition: Competition,
  margin: Level,
  trend: Trend,
  entry: Difficulty
): Rec {
  if (trend === "declining") return competition === "high" ? "not_now" : "test";
  if (competition === "high") {
    if (margin === "high" && entry !== "high") return "test";
    return "not_now";
  }
  // Launch only for clear asymmetric bets
  if (competition === "low" && margin === "high" && trend === "growing") return "launch";
  if (
    competition === "medium" &&
    margin === "high" &&
    trend === "growing" &&
    entry !== "high"
  ) {
    return "launch";
  }
  if (competition === "low" && margin === "high") return "test";
  if (competition === "medium") return "test";
  return "test";
}

function localizePrice(priceEn: string, country: string): string {
  if (cis.includes(country)) {
    if (priceEn.includes("RUB")) return priceEn;
    if (country === "KZ") return priceEn.replace(/RUB/g, "KZT equiv.");
    if (country === "UZ") return priceEn.replace(/RUB/g, "UZS equiv.");
    return priceEn;
  }
  if (country === "DE" || country === "NL") {
    return priceEn.replace(/\$/g, "€").replace(/USD/g, "EUR");
  }
  if (country === "GB") {
    return priceEn.replace(/\$/g, "£");
  }
  if (country === "AE") {
    return priceEn.includes("$") ? priceEn + " (or AED equiv.)" : priceEn;
  }
  if (country === "SA") {
    return priceEn.includes("$") ? priceEn + " (or SAR equiv.)" : priceEn;
  }
  return priceEn;
}

function build() {
  const rows = [];
  const now = new Date().toISOString();

  for (const t of templates) {
    for (const country of t.countries) {
      if (!country || country.length !== 2) continue;
      const mult = t.volumeMult?.[country] ?? (cis.includes(country) ? 0.4 : 0.65);
      const usBias = country === "US" ? 1 : mult;
      const volume = Math.max(
        50,
        Math.round(t.baseVolume * usBias * (0.9 + ((country.charCodeAt(0) % 7) * 0.02)))
      );
      const competition = t.competitionOverride?.[country] ?? t.competition;
      const recommendation =
        t.recOverride?.[country] ??
        recommend(competition, t.margin, t.trend, t.entry);

      rows.push({
        id: nanoid(10),
        countryCode: country,
        nicheId: t.nicheId,
        queryCluster: t.query,
        searchVolume: volume,
        trend: t.trend,
        competition,
        commercialIntent: t.intent,
        marginPotential: t.margin,
        entryDifficulty: t.entry,
        recommendation,
        exampleOffer: t.offerEn,
        exampleOfferRu: t.offerRu,
        priceRange: localizePrice(t.priceEn, country),
        source: "expert_estimate",
        confidence: competition === "low" ? 0.72 : competition === "medium" ? 0.68 : 0.64,
        updatedAt: now,
      });
    }
  }

  return rows;
}

